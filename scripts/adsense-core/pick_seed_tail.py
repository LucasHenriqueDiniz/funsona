"""Slice 3b of docs/plans/adsense-low-value-content: archive every seed quiz outside the curated core.

Why: 691 of the 762 published quizzes serve images hotlinked from quizpanda.com (PsyCat Games, a
third-party quiz site), 638 of them as the cover, which reads as a catalogue taken from it. The owner
decided (2026-10-18) to archive the whole seed tail outside the core, quizpanda images or not: the rest
came out of the same pipeline in the same 16 days. The core is rewritten in slice 4 instead.

Reads a sqlite copy of the quizzes table (a restored `wrangler d1 export`) and writes
archive-seed-tail.sql and seed-tail.csv next to this file. Touches no database.

Usage: python scripts/adsense-core/pick_seed_tail.py <restored-quizzes.sqlite>
"""
import csv
import json
import pathlib
import sqlite3
import sys

HERE = pathlib.Path(__file__).resolve().parent
SEED = "00000000-0000-0000-0000-000000000000"


def image_urls(content: dict, cover: str | None) -> list[str]:
    urls = [cover]
    for o in content.get("outcomes") or []:
        urls.append(o.get("imageUrl") or o.get("image_url") or o.get("image"))
    for q in content.get("questions") or []:
        urls.append(q.get("imageUrl") or q.get("image_url"))
        for a in (q.get("answers") or q.get("options") or []):
            urls.append(a.get("imageUrl") or a.get("image_url"))
    return [u for u in urls if isinstance(u, str) and u]


def quizpanda_count(content: str, cover: str | None) -> int:
    try:
        parsed = json.loads(content)
    except (TypeError, ValueError):
        parsed = {}
    return sum("quizpanda.com" in u for u in image_urls(parsed, cover))


def main(db_path: str) -> None:
    db = sqlite3.connect(db_path)
    published = db.execute(
        "SELECT slug, title, author_id, ads_eligible, cover_url, content FROM quizzes WHERE status = 'PUBLISHED'"
    ).fetchall()
    with_qp = sum(quizpanda_count(c, cov) > 0 for _, _, _, _, cov, c in published)
    core_qp = sum(quizpanda_count(c, cov) > 0 for _, _, _, f, cov, c in published if f == 1)
    tail = sorted(
        ({"slug": s, "title": t, "quizpanda_images": quizpanda_count(c, cov)}
         for s, t, a, f, cov, c in published if a == SEED and f == 0),
        key=lambda r: r["slug"],
    )
    with open(HERE / "seed-tail.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(tail[0]))
        w.writeheader()
        w.writerows(tail)
    slugs = ",\n  ".join("'" + r["slug"].replace("'", "''") + "'" for r in tail)
    (HERE / "archive-seed-tail.sql").write_text(f"""-- Slice 3b of docs/plans/adsense-low-value-content: archive the {len(tail)} seed quizzes outside the
-- curated core. Generated by pick_seed_tail.py; the list, with each quiz's quizpanda.com image
-- count, is seed-tail.csv. An archived quiz no longer resolves by slug; its page answers via /404.
-- Undo: the quizzes export taken 2026-10-19 00:50 UTC, or D1 Time Travel to before this write.
UPDATE quizzes
SET status = 'ARCHIVED',
    updated_at = STRFTIME('%Y-%m-%dT%H:%M:%fZ', 'now')
WHERE author_id = '{SEED}'
  AND status = 'PUBLISHED'
  AND ads_eligible = 0
  AND slug IN (
  {slugs}
);
""")
    n_qp = sum(r["quizpanda_images"] > 0 for r in tail)
    print(f"published with quizpanda images: {with_qp} of {len(published)} ({core_qp} in the core, rewritten in slice 4)")
    print(f"seed tail to archive: {len(tail)} ({n_qp} with quizpanda images, {len(tail) - n_qp} without)")


if __name__ == "__main__":
    main(sys.argv[1])
