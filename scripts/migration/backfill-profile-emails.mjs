/**
 * Backfills `profiles.email` in D1 from Supabase `auth.users`.
 *
 * Why this is needed: the D1 schema (0001) added an `email` column, but the
 * Supabase `profiles` table never had one — emails live in `auth.users`. So the
 * Supabase→D1 loader copies `r.email` as NULL for every row, and the migration
 * added in 0003 that claims a legacy profile by verified email has nothing to
 * match on. Without this backfill, every returning user gets a brand new empty
 * profile instead of their own.
 *
 * Emits SQL for `wrangler d1 execute`. Only writes rows where the Supabase auth
 * user has a CONFIRMED email — an unconfirmed address must never be usable to
 * claim an account.
 *
 *   node scripts/migration/backfill-profile-emails.mjs > backfill-emails.sql
 *   npx wrangler d1 execute funsona-db --local  --config apps/api/wrangler.toml --file backfill-emails.sql
 *   npx wrangler d1 execute funsona-db --remote --config apps/api/wrangler.toml --file backfill-emails.sql
 *
 * Requires SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY.
 */
const URL_ = process.env.SUPABASE_URL?.replace(/\/$/, "");
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!URL_ || !KEY) {
  console.error("Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY.");
  process.exit(1);
}
const headers = { apikey: KEY, Authorization: `Bearer ${KEY}` };

const sqlString = (value) => `'${String(value).replace(/'/g, "''")}'`;

async function fetchAuthUsers() {
  const users = [];
  for (let page = 1; ; page++) {
    const response = await fetch(`${URL_}/auth/v1/admin/users?page=${page}&per_page=200`, { headers });
    if (!response.ok) throw new Error(`auth admin ${response.status}: ${await response.text()}`);
    const batch = (await response.json()).users ?? [];
    users.push(...batch);
    if (batch.length < 200) return users;
  }
}

const users = await fetchAuthUsers();
const confirmed = users.filter((user) => user.email && user.email_confirmed_at);
const skipped = users.length - confirmed.length;

console.log("-- Backfills profiles.email from Supabase auth.users.");
console.log(`-- ${confirmed.length} users with a confirmed email; ${skipped} skipped as unconfirmed.`);
console.log("-- Generated by scripts/migration/backfill-profile-emails.mjs");
console.log();

for (const user of confirmed) {
  console.log(
    `UPDATE profiles SET email = ${sqlString(user.email)} WHERE id = ${sqlString(user.id)} AND email IS NULL;`
  );
}

console.error(`${confirmed.length} UPDATE statements written, ${skipped} unconfirmed users skipped.`);
